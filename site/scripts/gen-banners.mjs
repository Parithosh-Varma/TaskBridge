// Pre-render figlet banners at build time so the app ships static strings.
import figlet from 'figlet'
import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const outPath = join(here, '..', 'src', 'banners.js')

const WANT = {
  SUBMIT: 'Standard',
  QUEUE: 'Standard',
  EXECUTE: 'Standard',
  RETURN: 'Standard',
  'ASK BACK': 'Standard',
  CASE: 'Standard',
  MANIFEST: 'Standard',
  'WHY IT HOLDS': 'Standard',
}

const text = options =>
  new Promise((resolve, reject) =>
    figlet.text(options[0], { font: options[1] }, (err, data) =>
      err ? reject(err) : resolve(data),
    ),
  )

const normalize = art => {
  const lines = art.replace(/\r\n/g, '\n').split('\n')
  while (lines.length && lines[0].trim() === '') lines.shift()
  while (lines.length && lines[lines.length - 1].trim() === '') lines.pop()
  const width = Math.max(...lines.map(l => l.length))
  return lines.map(l => l.padEnd(width, ' ')).join('\n')
}

const entries = []
for (const [label, font] of Object.entries(WANT)) {
  entries.push(`  ${JSON.stringify(label)}: ${JSON.stringify(normalize(await text([label, font])))},`)
}

const body = `// Generated by scripts/gen-banners.mjs — do not edit by hand.
export const BANNERS = {
${entries.join('\n')}
}
`

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, body)
console.log(`wrote ${outPath}`)
